USE DATABASE CFB_TRANSFER_PORTAL_DEV;
USE SCHEMA _RAW;

-- Create rule to read API
CREATE OR REPLACE NETWORK RULE CFBD_API_RULE
  MODE = EGRESS
  TYPE = HOST_PORT
  VALUE_LIST = ('api.collegefootballdata.com');

-- Create Integration while referencing token in secrets
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION CFBD_API_INTEGRATION
  ALLOWED_NETWORK_RULES = (CFBD_API_RULE)
  ALLOWED_AUTHENTICATION_SECRETS = (CFB_TRANSFER_PORTAL_DEV._RAW.API_KEY)
  ENABLED = TRUE;

-- 3. Check to make sure actions are completed
SHOW NETWORK RULES;
SHOW SECRETS;
SHOW INTEGRATIONS LIKE 'CFBD%';